package com.gestaoInvetario.application.config;

import com.gestaoInvetario.application.security.CurrentUser;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.InitializingBean;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.orm.jpa.EntityManagerFactoryDependsOnPostProcessor;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.DelegatingDataSource;
import org.springframework.jdbc.datasource.init.DatabasePopulatorUtils;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

/**
 * Auditoria feita pelo banco, no formato do script do grupo (tabela Auditoria + triggers):
 * 1. antes do Hibernate, converte a tabela auditoria do formato antigo (Entidade/Acao/Resumo);
 * 2. em cada conexao, informa ao banco o usuario logado em app.id_funcionario (o @id_funcionario
 *    do script MySQL), lido pelos triggers;
 * 3. depois da inicializacao, (re)cria as funcoes e triggers de db/auditoria-triggers.sql.
 * So se aplica ao PostgreSQL; nos testes (H2) nada disso roda.
 */
@Configuration
public class AuditDatabaseConfig {

    private static final Logger log = LoggerFactory.getLogger(AuditDatabaseConfig.class);
    private static final String MIGRATION_BEAN = "auditoriaSchemaMigration";

    /** Garante que a conversao da tabela rode antes de o Hibernate validar/atualizar o schema. */
    @Bean
    static EntityManagerFactoryDependsOnPostProcessor auditoriaMigrationBeforeJpa() {
        return new EntityManagerFactoryDependsOnPostProcessor(MIGRATION_BEAN);
    }

    @Bean
    static BeanPostProcessor auditoriaUserDataSource() {
        return new BeanPostProcessor() {
            @Override
            public Object postProcessAfterInitialization(Object bean, String beanName) {
                return bean instanceof DataSource dataSource && !(bean instanceof SessionUserDataSource)
                        ? new SessionUserDataSource(dataSource)
                        : bean;
            }
        };
    }

    @Bean(MIGRATION_BEAN)
    InitializingBean auditoriaSchemaMigration(DataSource dataSource) {
        return () -> {
            try (Connection connection = dataSource.getConnection()) {
                if (isPostgres(connection)) {
                    migrate(connection);
                }
            }
        };
    }

    /** Antes do DataInitializer, para que as cargas iniciais tambem sejam auditadas. */
    @Bean
    @Order(Ordered.HIGHEST_PRECEDENCE)
    ApplicationRunner auditoriaTriggers(DataSource dataSource) {
        return args -> {
            try (Connection connection = dataSource.getConnection()) {
                if (!isPostgres(connection)) return;
            }
            ResourceDatabasePopulator populator = new ResourceDatabasePopulator(new ClassPathResource("db/auditoria-triggers.sql"));
            populator.setSeparator(";;");
            populator.setSqlScriptEncoding("UTF-8");
            DatabasePopulatorUtils.execute(populator, dataSource);
            log.info("Triggers de auditoria instalados.");
        };
    }

    private static boolean isPostgres(Connection connection) throws SQLException {
        return "PostgreSQL".equalsIgnoreCase(connection.getMetaData().getDatabaseProductName());
    }

    /** Cria a tabela no formato do script; se existir a versao antiga, converte os registros. */
    private static void migrate(Connection connection) throws SQLException {
        boolean legacy = hasColumn(connection, "auditoria", "entidade");
        boolean autoCommit = connection.getAutoCommit();
        connection.setAutoCommit(false);
        try (Statement st = connection.createStatement()) {
            if (legacy) {
                st.execute("ALTER TABLE auditoria RENAME TO auditoria_legado");
                st.execute("ALTER TABLE auditoria_legado RENAME CONSTRAINT auditoria_pkey TO auditoria_legado_pkey");
            }
            st.execute("""
                    CREATE TABLE IF NOT EXISTS auditoria (
                        seq             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        tabela_alterada varchar(30)  NOT NULL,
                        campo_alterado  varchar(20)  NOT NULL,
                        valor_anterior  varchar(100) NOT NULL,
                        valor_atual     varchar(100) NOT NULL,
                        dta_alteracao   timestamp(6) with time zone NOT NULL DEFAULT now(),
                        funcionario     integer,
                        usuario_banco   varchar(50)  NOT NULL
                    )""");
            st.execute("CREATE INDEX IF NOT EXISTS idx_auditoria_dta ON auditoria (dta_alteracao)");
            st.execute("CREATE INDEX IF NOT EXISTS idx_auditoria_tabela ON auditoria (tabela_alterada)");
            if (legacy) {
                // Cada acao antiga vira uma linha: o resumo vai para Valor_atual.
                int rows = st.executeUpdate("""
                        INSERT INTO auditoria (tabela_alterada, campo_alterado, valor_anterior, valor_atual,
                                               dta_alteracao, funcionario, usuario_banco)
                        SELECT CASE l.entidade
                                   WHEN 'PRODUTO' THEN 'Produto'
                                   WHEN 'CATEGORIA' THEN 'Categoria'
                                   WHEN 'USUARIO' THEN 'Funcionario'
                                   WHEN 'FORNECEDOR' THEN 'Fornecedor'
                                   WHEN 'LOCALIZACAO' THEN 'Localizacao'
                                   WHEN 'CONFIGURACAO' THEN 'Configuracao'
                                   ELSE left(initcap(l.entidade), 30) END,
                               CASE l.acao
                                   WHEN 'CRIACAO' THEN 'NOVO REGISTRO'
                                   WHEN 'EXCLUSAO' THEN 'REGISTRO DELETADO'
                                   WHEN 'DESATIVACAO' THEN 'Inativo'
                                   WHEN 'REATIVACAO' THEN 'Inativo'
                                   WHEN 'REATRIBUICAO' THEN 'Categoria'
                                   WHEN 'SENHA' THEN 'Senha'
                                   ELSE 'Cadastro' END,
                               'N/A',
                               CASE WHEN l.acao = 'SENHA' THEN '**********' ELSE left(l.resumo, 100) END,
                               l.dta_evento,
                               u.id,
                               current_user
                        FROM auditoria_legado l
                        LEFT JOIN usuario u ON u.login = l.usuario
                        ORDER BY l.dta_evento, l.id""");
                st.execute("DROP TABLE auditoria_legado");
                log.info("Tabela auditoria convertida para o formato do script ({} registros).", rows);
            }
            connection.commit();
        } catch (SQLException e) {
            connection.rollback();
            throw e;
        } finally {
            connection.setAutoCommit(autoCommit);
        }
    }

    private static boolean hasColumn(Connection connection, String table, String column) throws SQLException {
        try (PreparedStatement st = connection.prepareStatement("""
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?""")) {
            st.setString(1, table);
            st.setString(2, column);
            try (ResultSet rs = st.executeQuery()) {
                return rs.next();
            }
        }
    }

    /**
     * Ao entregar cada conexao do pool, grava o id do usuario logado em app.id_funcionario
     * (vazio fora de uma requisicao autenticada). Sempre sobrescrito, pois a conexao e reutilizada.
     */
    static final class SessionUserDataSource extends DelegatingDataSource {

        private volatile Boolean postgres;

        SessionUserDataSource(DataSource target) {
            super(target);
        }

        @Override
        public Connection getConnection() throws SQLException {
            return withSessionUser(super.getConnection());
        }

        @Override
        public Connection getConnection(String username, String password) throws SQLException {
            return withSessionUser(super.getConnection(username, password));
        }

        private Connection withSessionUser(Connection connection) throws SQLException {
            try {
                if (postgres == null) {
                    postgres = isPostgres(connection);
                }
                if (postgres) {
                    String employeeId = CurrentUser.get().map(user -> String.valueOf(user.id())).orElse("");
                    try (PreparedStatement st = connection.prepareStatement("SELECT set_config('app.id_funcionario', ?, false)")) {
                        st.setString(1, employeeId);
                        st.execute();
                    }
                }
                return connection;
            } catch (SQLException | RuntimeException e) {
                connection.close();
                throw e;
            }
        }
    }
}
